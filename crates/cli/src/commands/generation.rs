//! The `generate` command: continue a prompt without memory or learning.

use std::io::Write;

use thingamaroo_core::error::BrainResult;

use crate::arguments::GenerateArguments;
use crate::commands::Invocation;
use crate::commands::training::apply;
use crate::interrupt::install_interrupt_handler;
use crate::report::{describe_stop_reason, print_thoughts};

/// Continues a prompt, streaming the text as it is written.
pub fn generate(invocation: &Invocation, arguments: &GenerateArguments) -> BrainResult<()> {
    let mut brain = invocation.open_brain()?;
    let mut generation = brain.settings().generation.clone();
    apply(&mut generation.temperature, arguments.temperature);
    apply(&mut generation.candidate_count, arguments.candidates);
    apply(
        &mut generation.thinking_step_count,
        arguments.thinking_steps,
    );
    apply(
        &mut generation.maximum_reply_bytes,
        arguments.maximum_reply_bytes,
    );
    generation.seed = arguments.seed.or(generation.seed);
    let cancellation = install_interrupt_handler();

    print!("{}", arguments.prompt);
    let reply = brain.generate(
        &arguments.prompt,
        &generation,
        arguments.thoughts,
        &cancellation,
        &mut write_to_terminal,
    );
    println!();

    print_thoughts(&reply.thoughts);
    if let Some(reason) = describe_stop_reason(&reply) {
        println!("({reason})");
    }
    Ok(())
}

/// Writes generated bytes to the terminal the moment they exist.
pub(crate) fn write_to_terminal(bytes: &[u8]) {
    let mut terminal = std::io::stdout();
    // A closed terminal is not worth aborting a reply for; the text is still returned.
    let _ = terminal.write_all(bytes);
    let _ = terminal.flush();
}
